#!/usr/bin/env python3
"""Render CLAUDE.md's global-memory list from the one index that is authored by hand.

`claude/memory/MEMORY.md` is the single source: one line per memory file, every file exactly once.
An entry marked `{always}` is also written into `claude/CLAUDE.md`, which the harness injects into
every session — so that marker is the whole of the decision "must this fire unprompted, or is it
enough that it can be found?".

Two indexes were maintained by hand before this script, and they had drifted into two partial and
partly-contradictory lists: 68 entries in CLAUDE.md, 141 in MEMORY.md, 16 in both. The 125 that
existed only in MEMORY.md never reached a session at all, because nothing reads that file except
`/reflect`. Generating one from the other is what makes those two numbers impossible to disagree.

    python3 claude/scripts/render-memory-index.py            # rewrite CLAUDE.md's block
    python3 claude/scripts/render-memory-index.py --check     # exit 1 if it is stale (the commit gate)
"""

import argparse
import glob
import os
import re
import sys

ENTRY = re.compile(r'^- \[(?P<title>[^\]]+)\]\((?P<href>[^)]+\.md)\)(?P<flag> \{always\})? — (?P<blurb>.*?)\s*$')
LINK_PREFIX = "~/.claude/memory/"
BEGIN = "<!-- BEGIN generated by claude/scripts/render-memory-index.py — edit claude/memory/MEMORY.md, never this block -->"
END = "<!-- END generated -->"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
INDEX = os.path.join(ROOT, "claude", "memory", "MEMORY.md")
CLAUDE_MD = os.path.join(ROOT, "claude", "CLAUDE.md")


def read_lines(path: str) -> list[str]:
    with open(path, encoding="utf-8") as fh:
        return fh.read().split("\n")


def parse_index() -> tuple[list[re.Match[str]], list[str]]:
    """Every entry in file order, plus the problems that make the index untrustworthy.

    Coverage is checked in both directions. A memory nobody indexed is invisible; an entry whose
    file is gone is a link that resolves to nothing, and neither announces itself.
    """
    lines = read_lines(INDEX)
    entries, problems, seen = [], [], {}
    for n, line in enumerate(lines, 1):
        if not line.strip():
            continue
        m = ENTRY.match(line)
        if not m:
            problems.append(f"MEMORY.md:{n} is not an index entry: {line[:70]}")
            continue
        href = m.group("href")
        if href in seen:
            problems.append(f"MEMORY.md:{n} indexes {href} again (first at line {seen[href]})")
        seen[href] = n
        entries.append(m)

    on_disk = {os.path.basename(p) for p in glob.glob(os.path.join(ROOT, "claude", "memory", "*.md"))} - {"MEMORY.md"}
    for missing in sorted(on_disk - set(seen)):
        problems.append(f"claude/memory/{missing} is indexed nowhere, so nothing will ever surface it")
    for dangling in sorted(set(seen) - on_disk):
        problems.append(f"MEMORY.md:{seen[dangling]} points at {dangling}, which is not on disk")
    return entries, problems


def render(entries: list[re.Match[str]]) -> list[str]:
    return [BEGIN] + [f'- [{m.group("title")}]({LINK_PREFIX}{m.group("href")}) — {m.group("blurb")}'
                      for m in entries if m.group("flag")] + [END]


def splice(lines: list[str], block: list[str]) -> list[str]:
    try:
        start = lines.index(BEGIN)
        end = lines.index(END)
    except ValueError:
        raise SystemExit(f"CLAUDE.md has no generated block; add the {BEGIN!r} / {END!r} markers first")
    return lines[:start] + block + lines[end + 1:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="report staleness instead of fixing it")
    args = ap.parse_args()

    entries, problems = parse_index()
    for p in problems:
        print(f"  {p}")
    if problems:
        print(f"{len(problems)} problem(s) in claude/memory/MEMORY.md")
        return 1

    current = read_lines(CLAUDE_MD)
    updated = splice(current, render(entries))
    always = sum(1 for m in entries if m.group("flag"))
    if current == updated:
        print(f"{len(entries)} memories, {always} rendered into CLAUDE.md, block current")
        return 0
    if args.check:
        print("  CLAUDE.md's generated block does not match claude/memory/MEMORY.md")
        print("  run: python3 claude/scripts/render-memory-index.py")
        print(f"{len(entries)} memories, CLAUDE.md block STALE")
        return 1
    with open(CLAUDE_MD, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(updated))
    print(f"{len(entries)} memories, {always} rendered into CLAUDE.md, block rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
