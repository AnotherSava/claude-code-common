#!/bin/sh
# Ensure the openssl shim that silences transcrypt's "deprecated key derivation" warning exists, and print
# its path on stdout so a caller can wire it:
#
#   git config --local transcrypt.openssl-path "$(.../ensure-openssl-shim.sh)"
#
# Idempotent. Rewrites the shim when the real openssl has moved, so a machine that changed toolchains does
# not end up with a shim pointing at a binary that is gone. Everything diagnostic goes to stderr, so the
# command substitution above stays clean.
#
# The shim changes no crypto — same binary, same arguments, same exit status, byte-identical ciphertext.
# That is the point: patching openssl or switching the KDF would make this machine's blobs undecryptable by
# a machine running stock transcrypt. See SKILL.md for why the warning itself is not worth "fixing".
set -e

die() { printf '%s\n' "$*" >&2; exit 1; }

# The real openssl, resolved absolutely. PATH is walked by hand rather than with `command -v -a`, which is
# a bashism and silently yields nothing under a POSIX sh. Any shim found along the way is skipped, or a
# re-run once the shim sits on PATH would point it at itself and recurse until the stack gives out.
REAL=""
saved_ifs=$IFS
IFS=:
for dir in $PATH; do
    [ -n "$dir" ] || continue
    for candidate in "$dir/openssl" "$dir/openssl.exe"; do
        [ -f "$candidate" ] && [ -x "$candidate" ] || continue
        # A shell script here is a shim, not openssl. Only text files are inspected — grepping the real
        # binary would be meaningless and slow.
        if [ "$(head -c 2 "$candidate" 2>/dev/null)" = "#!" ]; then
            continue
        fi
        REAL="$candidate"; break
    done
    [ -n "$REAL" ] && break
done
IFS=$saved_ifs
[ -n "$REAL" ] || die "ensure-openssl-shim: no openssl on PATH"

# Live beside transcrypt: guaranteed to exist by the time this runs, and already a per-machine tools dir.
if command -v transcrypt >/dev/null 2>&1; then
    DIR=$(dirname "$(command -v transcrypt)")
else
    DIR=$(for d in "$HOME/.local/bin" "$HOME/bin" /usr/local/bin; do
        case ":$PATH:" in *":$d:"*) [ -d "$d" ] && echo "$d" && break ;; esac
    done)
fi
[ -n "$DIR" ] || die "ensure-openssl-shim: nowhere on PATH to put the shim"
SHIM="$DIR/openssl-transcrypt-quiet"

if [ -x "$SHIM" ] && grep -qF "REAL=$REAL" "$SHIM" 2>/dev/null; then
    printf '%s\n' "$SHIM"
    exit 0
fi

cat > "$SHIM" <<SHIMEOF
#!/bin/sh
# transcrypt shim — drops OpenSSL's "deprecated key derivation" warning and changes nothing else.
# Generated by ~/.claude/skills/transcrypt/scripts/ensure-openssl-shim.sh; edit that, not this.
REAL=$REAL

# stdout on fd 3 so binary ciphertext passes through unaltered — routing it through a shell variable would
# mangle it (NUL bytes, trailing newlines).
exec 3>&1
err="\$("\$REAL" "\$@" 2>&1 1>&3)"
rc=\$?
exec 3>&-

[ -n "\$err" ] && printf '%s\n' "\$err" \\
    | grep -vE '^\\*\\*\\* WARNING : deprecated key derivation used\\.\$|^Using -iter or -pbkdf2 would be better\\.\$' >&2

# openssl's status, never the filter's — anything scripted around these files must assert on this.
exit \$rc
SHIMEOF
chmod +x "$SHIM"
printf 'ensure-openssl-shim: wrote %s (openssl: %s)\n' "$SHIM" "$REAL" >&2
printf '%s\n' "$SHIM"
